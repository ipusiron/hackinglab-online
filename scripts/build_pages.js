#!/usr/bin/env node
"use strict";

// Generate the no-JavaScript page from the same catalog and book helpers as the hub.
const fs = require("node:fs");
const path = require("node:path");
const HB = require("../js/books.js");
const HU = require("../js/url.js");
const ROOT = path.resolve(__dirname, "..");

const COPY = Object.freeze({
  headingJa: "JavaScriptなしで読めるツール一覧",
  headingEn: "Tool list without JavaScript",
  titleJa: "JavaScriptなしで読めるツール一覧｜ハッキング・ラボ・オンライン",
  titleEn: "Tool list without JavaScript | Hacking Lab Online",
  introJa: "JavaScriptを使わずに読める、全ツールの一覧です。各ツールのデモとGitHubのREADMEを開けます（どちらも新しいタブで開きます）。絞り込みと進捗の記録は、トップのページで使えます。",
  introEn: "This list of all tools works without JavaScript. You can open each tool's demo and its README on GitHub (both open in a new tab). Filters and progress tracking are on the home page.",
  allJa: "すべてのツール（Day番号順）",
  allEn: "All tools (by Day number)",
  booksJa: "書籍・プロジェクトごとのツール",
  booksEn: "Tools by book or project",
  homeJa: "トップのページへ",
  homeEn: "Go to the home page"
});

const HOSTS = Object.freeze({
  repo: new Set(["github.com"]),
  demo: new Set(["ipusiron.github.io", "colab.research.google.com"]),
  book: new Set(["akademeia.info"])
});

function escapeHtml(value) {
  return String(value == null ? "" : value).replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

function safeUrl(value, kind) {
  if (typeof value !== "string" || !value || /[\u0000-\u0020\u007f\\]/.test(value)) throw new Error(`Unsafe ${kind} URL`);
  let url;
  try { url = new URL(value); } catch { throw new Error(`Unsafe ${kind} URL`); }
  if (url.protocol !== "https:" || url.username || url.password || url.port || !HOSTS[kind]?.has(url.hostname)) throw new Error(`Unsafe ${kind} URL`);
  return url.href;
}

function bilingual(ja, en) {
  return `<span lang="ja">${escapeHtml(ja)}</span><span lang="en">${escapeHtml(en)}</span>`;
}

function external(url, kind, label) {
  return `<a href="${escapeHtml(safeUrl(url, kind))}" target="_blank" rel="noopener noreferrer">${label}</a>`;
}

function toolRow(tool, id, book) {
  const titleLang = /[\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Han}]/u.test(tool.title) ? "ja" : "en";
  const links = [];
  if (tool.demo_url) links.push(external(tool.demo_url, "demo", bilingual("デモ", "Demo")));
  links.push(external(HU.repoLink(tool.repo_url, "ja", tool.readme_usage), "repo", "GitHub README"));
  const subtitle = tool.subtitle_ja || tool.subtitle_en
    ? `<div class="sl-subtitle">${bilingual(tool.subtitle_ja, tool.subtitle_en)}</div>` : "";
  const refs = book ? [HB.formatRef(book, tool.id, "ja"), HB.formatRef(book, tool.id, "en")] : [[], []];
  const references = refs[0].length || refs[1].length
    ? `<div class="sl-reference">${bilingual(refs[0].join("、"), refs[1].join("; "))}</div>` : "";
  return `          <li class="sl-row" id="${escapeHtml(id)}"><div class="sl-content"><div class="sl-tool-title"><span class="sl-day">Day${tool.id.slice(3)}</span> <strong lang="${titleLang}">${escapeHtml(tool.title)}</strong></div>${subtitle}${references}</div><div class="sl-links">${links.join("")}</div></li>`;
}

function buildPage(toolsData, booksData) {
  if (!toolsData || !Array.isArray(toolsData.tools)) throw new Error("tools.json must contain a tools array");
  const errors = HB.validateBooks(booksData, toolsData.tools);
  if (errors.length) throw new Error(errors.join("\n"));
  const seen = new Set();
  const tools = toolsData.tools.filter(t => t && t.hub !== false).slice();
  for (const tool of tools) {
    if (!/^day\d{3}$/.test(tool.id) || seen.has(tool.id)) throw new Error("Invalid or duplicate tool id");
    if (typeof tool.title !== "string" || !tool.title.trim()) throw new Error(`Missing title: ${tool.id}`);
    seen.add(tool.id);
    safeUrl(tool.repo_url, "repo");
    if (tool.demo_url) safeUrl(tool.demo_url, "demo");
  }
  tools.sort((a, b) => HB.dayNum(a.id) - HB.dayNum(b.id));
  const books = booksData.books;
  const lines = [
    "<!DOCTYPE html>", '<html lang="ja" class="sl-document">', "  <head>", '    <meta charset="UTF-8">',
    `    <title>${escapeHtml(COPY.titleJa)} / ${escapeHtml(COPY.titleEn)}</title>`,
    '    <meta name="viewport" content="width=device-width, initial-scale=1">',
    '    <meta http-equiv="Content-Security-Policy" content="default-src \'none\'; style-src \'self\'; img-src \'self\'; base-uri \'none\'; form-action \'none\'; object-src \'none\'">',
    '    <link rel="canonical" href="https://hackinglab.online/list.html">',
    '    <link rel="icon" href="./favicon/HLO.ico" sizes="any">',
    '    <link rel="stylesheet" href="./css/style.css">',
    '    <link rel="stylesheet" href="./css/list.css">', "  </head>", '  <body class="sl-page">',
    "    <!-- Generated by scripts/build_pages.js. Edit the generator or source data, then rebuild. -->",
    '    <header class="sl-header">', `      <a class="sl-home" href="./index.html">${bilingual(COPY.homeJa, COPY.homeEn)}</a>`,
    `      <h1>${bilingual(COPY.headingJa, COPY.headingEn)}</h1>`,
    `      <p lang="ja">${escapeHtml(COPY.introJa)}</p>`, `      <p lang="en">${escapeHtml(COPY.introEn)}</p>`,
    '      <nav class="sl-navigation">',
    `        <a href="#sl-all">${bilingual(COPY.allJa, COPY.allEn)}</a>`,
    `        <a href="#sl-books">${bilingual(COPY.booksJa, COPY.booksEn)}</a>`,
    "      </nav>", "    </header>", '    <main class="sl-main">', '      <section aria-labelledby="sl-all">',
    `        <h2 id="sl-all" tabindex="-1">${bilingual(COPY.allJa, COPY.allEn)}</h2>`, '        <ul class="sl-tool-list">',
    ...tools.map(t => toolRow(t, `sl-tool-${t.id}`)), "        </ul>", "      </section>",
    '      <section aria-labelledby="sl-books">', `        <h2 id="sl-books" tabindex="-1">${bilingual(COPY.booksJa, COPY.booksEn)}</h2>`,
    '        <nav class="sl-book-navigation" aria-labelledby="sl-books">',
    ...books.map(book => `          <a href="#sl-book-${escapeHtml(book.slug)}">${bilingual(HB.bookLabel(book, "ja"), HB.bookLabel(book, "en"))}</a>`),
    "        </nav>"
  ];
  for (const book of books) {
    const groups = HB.buildGroups(book, tools);
    const hasPages = groups.some(group => group.items.some(tool =>
      (book.refs?.[tool.id] || []).some(ref => HB.formatPages(ref.pages, "ja"))));
    lines.push(`        <section class="sl-book" aria-labelledby="sl-book-${escapeHtml(book.slug)}">`,
      `          <h3 id="sl-book-${escapeHtml(book.slug)}" tabindex="-1">${bilingual(HB.bookTitle(book, "ja"), HB.bookTitle(book, "en"))}</h3>`,
      `          <p class="sl-book-link">${external(book.url, "book", bilingual(book.url_label_ja + "（新しいタブ）", book.url_label_en + " (new tab)"))}</p>`);
    for (const name of ["note", "pages_note"]) {
      if (name === "pages_note" && !hasPages) continue;
      if (book[`${name}_ja`] || book[`${name}_en`]) lines.push(`          <p class="sl-note">${bilingual(book[`${name}_ja`], book[`${name}_en`])}</p>`);
    }
    for (const group of groups) {
      if (group.key) lines.push(`          <h4 id="sl-book-${escapeHtml(book.slug)}--chapter-${escapeHtml(group.key)}" tabindex="-1">${bilingual(HB.chapterTitle(book, group.key, "ja"), HB.chapterTitle(book, group.key, "en"))}</h4>`);
      lines.push('          <ul class="sl-tool-list">', ...group.items.map(t => toolRow(t, `sl-row-${book.slug}--${group.key || "all"}--${t.id}`, book)), "          </ul>");
    }
    lines.push("        </section>");
  }
  lines.push("      </section>", "    </main>", '    <footer class="sl-footer">', `      <a class="sl-home" href="./index.html">${bilingual(COPY.homeJa, COPY.homeEn)}</a>`, "    </footer>", "  </body>", "</html>", "");
  return lines.join("\n");
}

function main(args) {
  if (args.some(a => a !== "--check")) throw new Error("Usage: node scripts/build_pages.js [--check]");
  const toolsData = JSON.parse(fs.readFileSync(path.join(ROOT, "data/tools.json"), "utf8"));
  const booksData = JSON.parse(fs.readFileSync(path.join(ROOT, "data/books.json"), "utf8"));
  const output = buildPage(toolsData, booksData);
  const destination = path.join(ROOT, "list.html");
  const previous = fs.existsSync(destination) ? fs.readFileSync(destination, "utf8") : null;
  if (args.includes("--check")) {
    if (previous !== output) throw new Error("list.html is stale. Run npm run build:pages.");
    console.log("list.html matches the source data.");
  } else if (previous !== output) {
    fs.writeFileSync(destination, output, "utf8");
    console.log("Generated list.html.");
  } else console.log("list.html is unchanged.");
}

module.exports = { COPY, escapeHtml, safeUrl, buildPage };
if (require.main === module) {
  try { main(process.argv.slice(2)); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
